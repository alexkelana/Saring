function yahooSymbol(symbol) {
	const s = symbol.trim().toUpperCase();
	if (s === "^JKSE" || s === "COMPOSITE" || s === "IHSG") return "^JKSE";
	return s.endsWith(".JK") ? s : `${s}.JK`;
}
function bareSymbol(symbol) {
	return symbol.replace(/^\^/, "").replace(/\.JK$/i, "").toUpperCase();
}
function pickBacktestSymbols(sector = "Semua", limit = 24) {
	const rows = UNIVERSE.filter((s) => sector === "Semua" || s.sector === sector);
	const rank = (s) => (s.flags.idx30 ? 4 : 0) + (s.flags.lq45 ? 3 : 0) + (s.size === "mega" ? 3 : s.size === "large" ? 2 : s.size === "mid" ? 1 : 0);
	return [...rows].sort((a, b) => rank(b) - rank(a) || a.symbol.localeCompare(b.symbol)).slice(0, limit).map((s) => s.symbol);
}
